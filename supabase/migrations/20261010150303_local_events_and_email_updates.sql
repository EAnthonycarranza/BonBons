-- Public event information is separate from the private, confirmed email audience.
create table public.local_events (
  id bigint generated by default as identity primary key,
  title text not null check (length(trim(title)) between 1 and 120),
  description text not null default '' check (length(description)<=4000),
  venue text not null check (length(trim(venue)) between 1 and 160),
  address text not null check (length(trim(address)) between 1 and 300),
  event_date date not null, end_date date not null,
  start_time time, end_time time,
  image text not null default '', event_link text not null default '',
  status text not null default 'draft' check (status in ('draft','published','cancelled','archived')),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  check (end_date>=event_date),
  check (end_date>event_date or start_time is null or end_time is null or end_time>start_time)
);
create index local_events_status_date_idx on public.local_events(status,event_date);
alter table public.local_events enable row level security;
alter table public.local_events force row level security;
revoke all on public.local_events from public,anon,authenticated;
grant select on public.local_events to anon,authenticated;
grant all on public.local_events to service_role;
grant usage,select on sequence public.local_events_id_seq to service_role;
create policy local_events_public_read on public.local_events for select to anon,authenticated using(status in ('published','cancelled'));

alter table public.subscribers
  add column status text not null default 'pending' check(status in ('pending','active','unsubscribed')),
  add column event_opt_in boolean not null default false,
  add column consent_at timestamptz,
  add column confirmed_at timestamptz,
  add column unsubscribed_at timestamptz,
  add column confirmation_token_hash text,
  add column confirmation_expires_at timestamptz,
  add column confirmation_sent_at timestamptz,
  add column unsubscribe_token text not null default encode(extensions.gen_random_bytes(24),'hex') unique;
create index subscribers_event_audience_idx on public.subscribers(status) where event_opt_in and confirmed_at is not null;
create unique index subscribers_confirmation_token_idx on public.subscribers(confirmation_token_hash) where confirmation_token_hash is not null;
revoke all on public.subscribers from public,anon,authenticated;

create table public.event_email_campaigns (
  id bigint generated by default as identity primary key,
  design jsonb not null check(jsonb_typeof(design)='object'),
  status text not null default 'draft' check(status in ('draft','sending','sent')),
  snapshot jsonb,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  started_at timestamptz, completed_at timestamptz
);
create table public.event_email_deliveries (
  id uuid primary key default gen_random_uuid(),
  campaign_id bigint not null references public.event_email_campaigns(id),
  subscriber_id bigint not null references public.subscribers(id),
  status text not null default 'queued' check(status in ('queued','sending','sent','failed','skipped')),
  attempt_id uuid, claimed_at timestamptz, sent_at timestamptz,
  message_id text, error text,
  unique(campaign_id,subscriber_id)
);
create index event_email_deliveries_queue_idx on public.event_email_deliveries(campaign_id,status);
create index event_email_deliveries_subscriber_idx on public.event_email_deliveries(subscriber_id);
alter table public.event_email_campaigns enable row level security;
alter table public.event_email_campaigns force row level security;
alter table public.event_email_deliveries enable row level security;
alter table public.event_email_deliveries force row level security;
revoke all on public.event_email_campaigns,public.event_email_deliveries from public,anon,authenticated;
grant all on public.event_email_campaigns,public.event_email_deliveries to service_role;
grant usage,select on sequence public.event_email_campaigns_id_seq to service_role;

create function private.bonbons_event_updates(action text,payload jsonb)
returns jsonb language plpgsql security invoker set search_path=''
as $updates$
declare
  event public.local_events%rowtype;
  subscriber public.subscribers%rowtype;
  campaign public.event_email_campaigns%rowtype;
  delivery public.event_email_deliveries%rowtype;
  result jsonb;
  rows_out jsonb;
  design_in jsonb;
  token_hash text;
  ids bigint[];
  target bigint;
  email_in text;
  attempt uuid;
begin
  if action='event_list' then
    select coalesce(jsonb_agg(to_jsonb(e) order by e.event_date desc,e.id desc),'[]'::jsonb) into result from public.local_events e;
    return result;
  end if;
  if action='event_save' then
    if nullif(payload->>'id','') is null then
      insert into public.local_events(title,description,venue,address,event_date,end_date,start_time,end_time,image,event_link,status)
      values(payload->>'title',coalesce(payload->>'description',''),payload->>'venue',payload->>'address',(payload->>'event_date')::date,(payload->>'end_date')::date,
        nullif(payload->>'start_time','')::time,nullif(payload->>'end_time','')::time,coalesce(payload->>'image',''),coalesce(payload->>'event_link',''),coalesce(payload->>'status','draft')) returning * into event;
    else
      update public.local_events set title=payload->>'title',description=coalesce(payload->>'description',''),venue=payload->>'venue',address=payload->>'address',event_date=(payload->>'event_date')::date,end_date=(payload->>'end_date')::date,
        start_time=nullif(payload->>'start_time','')::time,end_time=nullif(payload->>'end_time','')::time,image=coalesce(payload->>'image',''),event_link=coalesce(payload->>'event_link',''),status=payload->>'status',updated_at=now()
        where id=(payload->>'id')::bigint returning * into event;
      if not found then raise exception 'Event not found.' using errcode='P0002'; end if;
    end if;
    return to_jsonb(event);
  end if;
  if action='subscriber_list' then
    select coalesce(jsonb_agg(to_jsonb(s) order by s.created_at desc,s.id desc),'[]'::jsonb) into result from
      (select id,email,source,status,event_opt_in,consent_at,confirmed_at,created_at,unsubscribed_at from public.subscribers order by created_at desc,id desc limit 5000) s;
    return result;
  end if;
  if action='subscriber_unsubscribe_admin' then
    update public.subscribers set status='unsubscribed',event_opt_in=false,unsubscribed_at=now(),confirmation_token_hash=null,updated_at=now() where id=(payload->>'id')::bigint returning * into subscriber;
    if not found then raise exception 'Subscriber not found.' using errcode='P0002'; end if;
    return jsonb_build_object('id',subscriber.id,'status',subscriber.status);
  end if;
  if action='subscriber_request' then
    email_in:=lower(trim(payload->>'email'));
    if email_in is null or length(email_in)>254 or email_in !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' or coalesce(payload->>'token','') !~ '^[0-9a-f]{48}$' then
      raise exception 'A valid email and confirmation token are required.' using errcode='22023';
    end if;
    insert into public.subscribers(email,source) values(email_in,case when payload->>'source'='events' then 'events' else 'homepage' end) on conflict(email) do nothing;
    select * into subscriber from public.subscribers where email=email_in for update;
    if subscriber.status='active' or subscriber.confirmation_sent_at>now()-interval '5 minutes' then return jsonb_build_object('send',false); end if;
    token_hash:=encode(extensions.digest(payload->>'token','sha256'),'hex');
    update public.subscribers set status='pending',event_opt_in=true,consent_at=now(),confirmation_token_hash=token_hash,
      confirmation_expires_at=now()+interval '48 hours',confirmation_sent_at=now(),updated_at=now() where id=subscriber.id;
    return jsonb_build_object('send',true);
  end if;
  if action='subscriber_confirmation_failed' then
    update public.subscribers set confirmation_sent_at=null where confirmation_token_hash=encode(extensions.digest(payload->>'token','sha256'),'hex') and status='pending';
    return jsonb_build_object('ok',true);
  end if;
  if action='subscriber_confirm' then
    select * into subscriber from public.subscribers where confirmation_token_hash=encode(extensions.digest(payload->>'token','sha256'),'hex') for update;
    if not found or subscriber.confirmation_expires_at<now() or subscriber.status='unsubscribed' or not subscriber.event_opt_in then
      raise exception 'This confirmation link is invalid or expired. Sign up again to get a fresh link.' using errcode='22023';
    end if;
    update public.subscribers set status='active',confirmed_at=coalesce(confirmed_at,now()),unsubscribed_at=null,updated_at=now() where id=subscriber.id;
    return jsonb_build_object('ok',true);
  end if;
  if action='subscriber_unsubscribe' then
    update public.subscribers set status='unsubscribed',event_opt_in=false,unsubscribed_at=coalesce(unsubscribed_at,now()),confirmation_token_hash=null,updated_at=now() where unsubscribe_token=payload->>'token' returning * into subscriber;
    if not found then raise exception 'This unsubscribe link is invalid.' using errcode='22023'; end if;
    return jsonb_build_object('ok',true);
  end if;
  if action='event_campaign_list' then
    select coalesce(jsonb_agg(to_jsonb(c) order by c.created_at desc,c.id desc),'[]'::jsonb) into result from
      (select id,design,status,created_at,updated_at,started_at,completed_at from public.event_email_campaigns) c;
    return result;
  end if;
  if action='event_campaign_save' then
    design_in:=payload->'design';
    if jsonb_typeof(design_in) is distinct from 'object' or coalesce(length(trim(design_in->>'subject')),0) not between 1 and 150 or coalesce(length(trim(design_in->>'headline')),0) not between 1 and 160
      or length(design_in->>'message')>6000 or design_in->>'accent' !~ '^#[0-9a-fA-F]{6}$' or design_in->>'layout' not in ('spotlight','digest','brief')
      or jsonb_typeof(design_in->'eventIds') is distinct from 'array' or jsonb_array_length(design_in->'eventIds')>12 then
      raise exception 'Choose a valid email design.' using errcode='22023';
    end if;
    if nullif(payload->>'id','') is null then
      insert into public.event_email_campaigns(design) values(design_in) returning * into campaign;
    else
      update public.event_email_campaigns set design=design_in,updated_at=now() where id=(payload->>'id')::bigint and status='draft' returning * into campaign;
      if not found then raise exception 'Only draft emails can be edited. Create a new update.' using errcode='22023'; end if;
    end if;
    return to_jsonb(campaign)-'snapshot';
  end if;
  if action='event_campaign_begin' then
    select * into campaign from public.event_email_campaigns where id=(payload->>'id')::bigint for update;
    if not found then raise exception 'Email draft not found.' using errcode='P0002'; end if;
    if campaign.status='draft' then
      select array_agg(value::bigint) into ids from jsonb_array_elements_text(campaign.design->'eventIds');
      if coalesce(array_length(ids,1),0)=0 or exists(select 1 from unnest(ids) id where not exists(select 1 from public.local_events e where e.id=id and e.status in ('published','cancelled'))) then
        raise exception 'Choose at least one published or cancelled event before sending.' using errcode='22023';
      end if;
      if not exists(select 1 from public.subscribers where status='active' and event_opt_in and confirmed_at is not null) then
        raise exception 'No confirmed subscribers have opted in yet.' using errcode='22023';
      end if;
      select jsonb_agg(to_jsonb(e) order by array_position(ids,e.id)) into rows_out from public.local_events e where e.id=any(ids);
      update public.event_email_campaigns set snapshot=jsonb_build_object('design',design,'events',rows_out),status='sending',started_at=now(),updated_at=now() where id=campaign.id;
      insert into public.event_email_deliveries(campaign_id,subscriber_id)
        select campaign.id,id from public.subscribers where status='active' and event_opt_in and confirmed_at is not null on conflict do nothing;
    end if;
    return jsonb_build_object('id',campaign.id);
  end if;
  if action='event_campaign_status' then
    target:=(payload->>'id')::bigint;
    if not exists(select 1 from public.event_email_campaigns where id=target) then raise exception 'Email draft not found.' using errcode='P0002'; end if;
    select jsonb_build_object('id',target,'status',(select status from public.event_email_campaigns where id=target),
      'total',count(*),'queued',count(*) filter(where status='queued'),'sending',count(*) filter(where status='sending'),
      'sent',count(*) filter(where status='sent'),'failed',count(*) filter(where status='failed'),'skipped',count(*) filter(where status='skipped'),
      'stalled',count(*) filter(where status='sending' and claimed_at<now()-interval '5 minutes')) into result from public.event_email_deliveries where campaign_id=target;
    return result;
  end if;
  if action='event_campaign_claim' then
    select * into campaign from public.event_email_campaigns where id=(payload->>'id')::bigint;
    if not found or campaign.status<>'sending' then return '[]'::jsonb; end if;
    result:='[]'::jsonb;
    for delivery in select * from public.event_email_deliveries where campaign_id=campaign.id and status='queued' order by id for update skip locked limit 3 loop
      select * into subscriber from public.subscribers where id=delivery.subscriber_id;
      if subscriber.status<>'active' or not subscriber.event_opt_in or subscriber.confirmed_at is null then
        update public.event_email_deliveries set status='skipped' where id=delivery.id;
      else
        attempt:=gen_random_uuid();
        update public.event_email_deliveries set status='sending',attempt_id=attempt,claimed_at=now(),error=null where id=delivery.id;
        result:=result||jsonb_build_array(jsonb_build_object('id',delivery.id,'attempt',attempt,'email',subscriber.email,'unsubscribeToken',subscriber.unsubscribe_token,'snapshot',campaign.snapshot));
      end if;
    end loop;
    if not exists(select 1 from public.event_email_deliveries where campaign_id=campaign.id and status in ('queued','sending')) then
      update public.event_email_campaigns set status='sent',completed_at=now(),updated_at=now() where id=campaign.id;
    end if;
    return result;
  end if;
  if action='event_delivery_check' then
    return jsonb_build_object('active',exists(select 1 from public.event_email_deliveries d join public.subscribers s on s.id=d.subscriber_id
      where d.id=(payload->>'id')::uuid and d.attempt_id=(payload->>'attempt')::uuid and d.status='sending' and s.status='active' and s.event_opt_in and s.confirmed_at is not null));
  end if;
  if action='event_delivery_finish' then
    if payload->>'status' not in ('sent','failed','skipped') then raise exception 'Invalid delivery result.' using errcode='22023'; end if;
    update public.event_email_deliveries set status=payload->>'status',message_id=left(payload->>'messageId',300),error=left(payload->>'error',500),
      sent_at=case when payload->>'status'='sent' then now() else null end where id=(payload->>'id')::uuid and attempt_id=(payload->>'attempt')::uuid and status='sending' returning * into delivery;
    if not found then raise exception 'This delivery attempt is no longer current.' using errcode='22023'; end if;
    if not exists(select 1 from public.event_email_deliveries where campaign_id=delivery.campaign_id and status in ('queued','sending')) then
      update public.event_email_campaigns set status='sent',completed_at=now(),updated_at=now() where id=delivery.campaign_id;
    end if;
    return jsonb_build_object('ok',true);
  end if;
  if action='event_campaign_retry' then
    select * into campaign from public.event_email_campaigns where id=(payload->>'id')::bigint for update;
    if not found or campaign.status='draft' then raise exception 'No deliveries to retry.' using errcode='22023'; end if;
    update public.event_email_deliveries set status='queued',attempt_id=null,claimed_at=null,error=null where campaign_id=campaign.id
      and (status='failed' or (status='sending' and claimed_at<now()-interval '5 minutes'));
    if found then update public.event_email_campaigns set status='sending',completed_at=null,updated_at=now() where id=campaign.id; end if;
    return jsonb_build_object('ok',true);
  end if;
  raise exception 'Unknown event update action.' using errcode='22023';
end
$updates$;
revoke all on function private.bonbons_event_updates(text,jsonb) from public,anon,authenticated,service_role;

do $extend$
declare definition text;
begin
  select pg_get_functiondef('public.bonbons_admin(text,text,jsonb)'::regprocedure) into definition;
  if position('if action = ''list_weekly_boxes'' then' in definition)=0 then raise exception 'Apply earlier BonBons migrations first.'; end if;
  definition:=replace(definition,'if action = ''list_weekly_boxes'' then',
    'if action in (''event_list'',''event_save'',''subscriber_list'',''subscriber_unsubscribe_admin'',''subscriber_request'',''subscriber_confirmation_failed'',''subscriber_confirm'',''subscriber_unsubscribe'',''event_campaign_list'',''event_campaign_save'',''event_campaign_begin'',''event_campaign_status'',''event_campaign_claim'',''event_delivery_check'',''event_delivery_finish'',''event_campaign_retry'') then
    return private.bonbons_event_updates(action,payload);
  end if;

  if action = ''list_weekly_boxes'' then');
  execute definition;
end
$extend$;
notify pgrst,'reload schema';
