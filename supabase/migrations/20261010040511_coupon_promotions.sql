-- All codes with the same normalized campaign name belong to one promotion.
-- Keep the customer limit even when staff delete an order. The unique key
-- also serializes requests using different codes from the same promotion.
alter table public.coupons add column promotion_key text generated always as
  (lower(regexp_replace(trim(name), '\s+', ' ', 'g'))) stored;

create table public.coupon_redemptions (
  id bigint generated by default as identity primary key,
  coupon_id bigint not null references public.coupons(id),
  order_id bigint unique references public.orders(id) on delete set null,
  promotion_key text not null,
  customer_email text not null check (customer_email = lower(trim(customer_email))),
  redeemed_at timestamptz not null default now(),
  unique (promotion_key, customer_email)
);
create index coupon_redemptions_coupon_id_idx on public.coupon_redemptions(coupon_id);
alter table public.coupon_redemptions enable row level security;
alter table public.coupon_redemptions force row level security;
revoke all on public.coupon_redemptions from public, anon, authenticated;
grant all on public.coupon_redemptions to service_role;
grant usage, select on sequence public.coupon_redemptions_id_seq to service_role;

insert into public.coupon_redemptions(coupon_id, order_id, promotion_key, customer_email, redeemed_at)
select distinct on (c.promotion_key, lower(trim(o.customer_email))) c.id, o.id,
  c.promotion_key, lower(trim(o.customer_email)), o.created_at
from public.orders o join public.coupons c on c.id=o.coupon_id
order by c.promotion_key, lower(trim(o.customer_email)), o.created_at, o.id;

