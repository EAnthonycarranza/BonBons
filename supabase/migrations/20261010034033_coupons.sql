-- Physical coupon codes are private. Only the existing token-guarded admin RPC
-- may call the helper; previewing never consumes a use. Saving an order locks
-- its coupon and records the discount and redemption in one transaction.
create table public.coupons (
  id bigint generated by default as identity primary key,
  code text not null unique check (code ~ '^[A-Z0-9][A-Z0-9-]{2,30}[A-Z0-9]$'),
  name text not null check (length(trim(name)) between 1 and 80),
  discount_amount numeric(10,2) not null check (discount_amount between 0.01 and 500),
  minimum_subtotal numeric(10,2) not null default 0 check (minimum_subtotal between 0 and 100000),
  max_redemptions integer not null default 1 check (max_redemptions between 1 and 1000000),
  redemption_count integer not null default 0 check (redemption_count between 0 and max_redemptions),
  expires_on date,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.coupons enable row level security;
alter table public.coupons force row level security;
revoke all on public.coupons from public, anon, authenticated;
grant all on public.coupons to service_role;
grant usage, select on sequence public.coupons_id_seq to service_role;

alter table public.orders
  add column coupon_id bigint references public.coupons(id) on delete set null,
  add column coupon_code text,
  add column discount_amount numeric(10,2) not null default 0 check (discount_amount >= 0),
  add column subtotal_before_discount numeric(10,2),
  add column coupon_request_id uuid unique,
  add constraint orders_coupon_totals_check check (
    subtotal_before_discount is null or (
      subtotal_before_discount >= 0 and
      discount_amount <= subtotal_before_discount and
      subtotal = subtotal_before_discount - discount_amount
    )
  );

create index orders_coupon_id_idx on public.orders(coupon_id) where coupon_id is not null;

create or replace function private.bonbons_coupons(action text, payload jsonb)
returns jsonb language plpgsql security invoker set search_path = ''
as $coupons$
declare
  coupon public.coupons%rowtype;
  saved_order public.orders%rowtype;
  requested_code text := upper(trim(coalesce(payload ->> 'code', '')));
  original_total numeric(10,2);
  discount numeric(10,2);
  order_in jsonb;
  request_id uuid;
  result jsonb;
  code_in text;
begin
  if action = 'coupon_list' then
    select coalesce(jsonb_agg(to_jsonb(c) order by c.created_at desc, c.id desc), '[]'::jsonb)
      into result from public.coupons c;
    return result;
  end if;

  if action = 'coupon_create' then
    if jsonb_typeof(payload -> 'codes') is distinct from 'array'
       or jsonb_array_length(payload -> 'codes') not between 1 and 200 then
      raise exception 'Generate between 1 and 200 codes at a time.' using errcode = '22023';
    end if;
    if nullif(payload ->> 'expires_on', '')::date < (now() at time zone 'America/Chicago')::date then
      raise exception 'The expiration date cannot be in the past.' using errcode = '22023';
    end if;
    result := '[]'::jsonb;
    for code_in in select jsonb_array_elements_text(payload -> 'codes') loop
      insert into public.coupons (code, name, discount_amount, minimum_subtotal, max_redemptions, expires_on)
      values (upper(trim(code_in)), trim(payload ->> 'name'),
        (payload ->> 'discount_amount')::numeric,
        coalesce((payload ->> 'minimum_subtotal')::numeric, 0),
        coalesce((payload ->> 'max_redemptions')::integer, 1),
        nullif(payload ->> 'expires_on', '')::date)
      returning * into coupon;
      result := result || jsonb_build_array(to_jsonb(coupon));
    end loop;
    return result;
  end if;

  if action = 'coupon_update' then
    if jsonb_typeof(payload -> 'active') is distinct from 'boolean' then
      raise exception 'Choose whether this coupon is active.' using errcode = '22023';
    end if;
    update public.coupons set active = (payload ->> 'active')::boolean
      where id = (payload ->> 'id')::bigint returning * into coupon;
    if not found then raise exception 'Coupon not found.' using errcode = 'P0002'; end if;
    return to_jsonb(coupon);
  end if;

  if action not in ('coupon_preview', 'coupon_order') then
    raise exception 'Unknown coupon action.' using errcode = '22023';
  end if;
  if action = 'coupon_order' then
    order_in := payload -> 'order';
    request_id := (payload ->> 'request_id')::uuid;
    if request_id is null then raise exception 'A request ID is required.' using errcode = '22023'; end if;
    original_total := (order_in ->> 'subtotal')::numeric;
    select * into coupon from public.coupons where code = requested_code for update;
  else
    original_total := (payload ->> 'subtotal')::numeric;
    select * into coupon from public.coupons where code = requested_code;
  end if;
  if not found then
    raise exception 'This coupon code is invalid or no longer available.' using errcode = '22023';
  end if;

  -- The lock also serializes retries for the same coupon. A lost HTTP response
  -- cannot consume a second use or send a second receipt for an unchanged request.
  if action = 'coupon_order' then
    select * into saved_order from public.orders where coupon_request_id = request_id;
    if found then
      if saved_order.coupon_code <> requested_code
         or saved_order.customer_email <> lower(trim(order_in ->> 'customer_email'))
         or saved_order.customer_name <> trim(order_in ->> 'customer_name')
         or saved_order.customer_phone <> trim(order_in ->> 'customer_phone')
         or saved_order.wanted_date <> (order_in ->> 'wanted_date')::date
         or saved_order.notes <> coalesce(order_in ->> 'notes', '')
         or saved_order.items <> (order_in -> 'items')
         or saved_order.subtotal_before_discount <> original_total then
        raise exception 'This request has changed. Please try again.' using errcode = '22023';
      end if;
      return jsonb_build_object('data', to_jsonb(saved_order), 'replayed', true);
    end if;
  end if;

  if not coupon.active or coupon.redemption_count >= coupon.max_redemptions
     or coupon.expires_on < (now() at time zone 'America/Chicago')::date then
    raise exception 'This coupon code is invalid or no longer available.' using errcode = '22023';
  end if;
  if original_total is null or original_total < 0 or original_total = 'NaN'::numeric then
    raise exception 'The order total is invalid.' using errcode = '22023';
  end if;
  if original_total < coupon.minimum_subtotal then
    raise exception 'This coupon requires an order of at least $%.', coupon.minimum_subtotal using errcode = '22023';
  end if;
  discount := least(coupon.discount_amount, original_total);
  if action = 'coupon_preview' then
    return jsonb_build_object('code', coupon.code, 'discountAmount', discount,
      'originalSubtotal', original_total, 'subtotal', original_total - discount);
  end if;

  insert into public.orders (items, subtotal, subtotal_before_discount, discount_amount,
    coupon_id, coupon_code, coupon_request_id, customer_name, customer_email,
    customer_phone, fulfilment, wanted_date, notes, payment_status)
  values (order_in -> 'items', original_total - discount, original_total, discount,
    coupon.id, coupon.code, request_id, trim(order_in ->> 'customer_name'),
    lower(trim(order_in ->> 'customer_email')), trim(order_in ->> 'customer_phone'),
    'Pickup', (order_in ->> 'wanted_date')::date, coalesce(order_in ->> 'notes', ''),
    case when payload ->> 'payment_choice' = 'cash' then 'cash_at_pickup' else 'not_arranged' end)
  returning * into saved_order;
  update public.coupons set redemption_count = redemption_count + 1 where id = coupon.id;
  return jsonb_build_object('data', to_jsonb(saved_order), 'replayed', false);
end
$coupons$;
revoke all on function private.bonbons_coupons(text, jsonb) from public, anon, authenticated, service_role;

-- Extend the existing guarded entry point after its token check. The helper
-- stays in a non-exposed schema and cannot be called directly by public roles.
do $extend$
declare definition text;
begin
  select pg_get_functiondef(p.oid) into definition from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname = 'bonbons_admin';
  if definition is null or position('if action = ''list_weekly_boxes'' then' in definition) = 0 then
    raise exception 'Apply the earlier BonBons migrations first.';
  end if;
  if position('private.bonbons_coupons' in definition) = 0 then
    definition := replace(definition, 'if action = ''list_weekly_boxes'' then',
      'if action in (''coupon_list'', ''coupon_create'', ''coupon_update'', ''coupon_preview'', ''coupon_order'') then
    return private.bonbons_coupons(action, payload);
  end if;

  if action = ''list_weekly_boxes'' then');
    execute definition;
  end if;
end
$extend$;
notify pgrst, 'reload schema';
