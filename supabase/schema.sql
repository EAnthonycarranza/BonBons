-- Bon Bon's data model. The same DDL is applied to the linked Supabase project.
-- Product rows are public and read-only. Customer data is private and is only
-- accessed through the authenticated bonbons-data Edge Function.

create schema if not exists private;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  blurb text not null default '',
  description text not null default '',
  price numeric(10, 2) not null check (price >= 0),
  unit text not null default '',
  bundle_eligible boolean not null default false,
  image text not null default '',
  icon text not null default 'i-cakepop',
  color text not null default '#FF2E9A',
  tint text not null default '255,46,154',
  badge text not null default '',
  badge_class text not null default '',
  category text not null default 'everyday',
  lead_time_hours integer not null default 72 check (lead_time_hours >= 0),
  allergens text[] not null default '{}',
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists products_public_catalog_idx
  on public.products (active, sort_order, name);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  items jsonb not null check (jsonb_typeof(items) = 'array' and jsonb_array_length(items) > 0),
  subtotal numeric(10, 2) not null default 0 check (subtotal >= 0),
  customer_name text not null,
  customer_email text not null,
  customer_phone text not null,
  fulfilment text not null default 'Pickup' check (fulfilment = 'Pickup'),
  wanted_date date not null,
  notes text not null default '',
  admin_notes text not null default '',
  payment_status text not null default 'not_arranged'
    check (payment_status in ('not_arranged', 'instructions_sent', 'paid_cash', 'paid_direct')),
  status text not null default 'pending'
    check (status in ('pending', 'contacted', 'confirmed', 'preparing', 'ready', 'collected', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists orders_status_created_at_idx
  on public.orders (status, created_at desc);
create index if not exists orders_created_at_idx
  on public.orders (created_at desc);

create table if not exists public.quotes (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text not null,
  event_date date not null,
  occasion text not null default '',
  guests integer check (guests is null or guests > 0),
  fulfilment text not null default 'Pickup' check (fulfilment = 'Pickup'),
  zip text not null default '',
  interests text[] not null default '{}',
  colors text not null default '',
  notes text not null default '',
  admin_notes text not null default '',
  payment_status text not null default 'not_arranged'
    check (payment_status in ('not_arranged', 'instructions_sent', 'paid_cash', 'paid_direct')),
  status text not null default 'new'
    check (status in ('new', 'contacted', 'quoted', 'booked', 'preparing', 'ready', 'closed', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists quotes_status_created_at_idx
  on public.quotes (status, created_at desc);
create index if not exists quotes_created_at_idx
  on public.quotes (created_at desc);

create table if not exists public.subscribers (
  id bigint generated by default as identity primary key,
  email text not null unique check (email = lower(email)),
  source text not null default 'site',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.pickup_locations (
  id bigint generated by default as identity primary key,
  label text not null check (length(trim(label)) > 0),
