create or replace function private.assign_order_confirmation()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  confirmation_status text;
begin
  confirmation_status := case when tg_table_name = 'orders' then 'confirmed' else 'booked' end;

  if new.status = confirmation_status and new.order_number is null then
    new.order_number :=
      'BB-' || to_char(current_date, 'YY') || '-' ||
      lpad(nextval('private.order_number_seq'::regclass)::text, 4, '0');
    new.confirmed_at := coalesce(new.confirmed_at, now());

    if tg_table_name = 'orders' then
      new.confirmed_total := coalesce(new.confirmed_total, new.subtotal);
      new.pickup_date := coalesce(new.pickup_date, new.wanted_date);
    else
      new.pickup_date := coalesce(new.pickup_date, new.event_date);
    end if;
  end if;

  return new;
end;
$$;

revoke all on function private.assign_order_confirmation() from public, anon, authenticated;
grant usage on schema private to service_role;
grant usage, select, update on sequence private.order_number_seq to service_role;
grant execute on function private.assign_order_confirmation() to service_role;

drop trigger if exists assign_order_confirmation_on_orders on public.orders;
create trigger assign_order_confirmation_on_orders
  before insert or update of status, order_number
  on public.orders
  for each row
  execute function private.assign_order_confirmation();

